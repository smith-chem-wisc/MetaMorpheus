using EngineLayer.DatabaseLoading;
using NUnit.Framework;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;
using TaskLayer;

namespace Test
{
    /// <summary>
    /// Calibration loads its database in the background while the first spectra file is read, and writes the prose that
    /// names the database once the load is done. The prose must come out as it did when the database was loaded first:
    /// complete, once, and also when no file could be calibrated at all.
    /// </summary>
    [TestFixture]
    internal static class CalibrationDatabaseOverlapTest
    {
        private const string ExpectedProseStart = "The following calibration settings were used: ";

        [Test]
        public static void CalibrationWritesTheDatabaseProseOnce()
        {
            string folder = Path.Combine(TestContext.CurrentContext.TestDirectory, "CalibrationDatabaseOverlapTest_calibrated");
            string spectra = Path.Combine(TestContext.CurrentContext.TestDirectory, "TestData", "SmallCalibratible_Yeast.mzML");
            string prose = RunCalibration(folder, spectra, out int targets);

            Assert.That(Regex.Matches(prose, Regex.Escape(ExpectedProseStart)).Count, Is.EqualTo(1));
            Assert.That(Regex.Matches(prose, $"The combined search database contained {targets} non-decoy protein entries including 0 contaminant sequences. ").Count,
                Is.EqualTo(1));
            Assert.That(File.Exists(Path.Combine(folder, "SmallCalibratible_Yeast-calib.mzML")));
            Directory.Delete(folder, true);
        }

        [Test]
        public static void CalibrationWithNoCalibratableFileStillLoadsTheDatabase()
        {
            string folder = Path.Combine(TestContext.CurrentContext.TestDirectory, "CalibrationDatabaseOverlapTest_mgf");
            string spectra = Path.Combine(TestContext.CurrentContext.TestDirectory, "TestData", "ok.mgf");
            string prose = RunCalibration(folder, spectra, out int targets);

            Assert.That(targets, Is.GreaterThan(0));
            Assert.That(Regex.Matches(prose, Regex.Escape(ExpectedProseStart)).Count, Is.EqualTo(1));
            Assert.That(Regex.Matches(prose, $"The combined search database contained {targets} non-decoy protein entries").Count, Is.EqualTo(1));
            Directory.Delete(folder, true);
        }

        private static string RunCalibration(string folder, string spectra, out int targets)
        {
            if (Directory.Exists(folder))
            {
                Directory.Delete(folder, true);
            }
            Directory.CreateDirectory(folder);
            string database = Path.Combine(TestContext.CurrentContext.TestDirectory, "TestData", "smalldb.fasta");

            var db = new DbForTask(database, false);
            new CalibrationTask().RunTask(folder, new List<DbForTask> { db }, new List<string> { spectra }, "test");
            targets = db.TargetCount ?? -1;
            return File.ReadAllText(Path.Combine(folder, "AutoGeneratedManuscriptProse.txt"));
        }
    }
}
